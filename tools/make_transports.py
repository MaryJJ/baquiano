"""Generates Baquiano/TransportData.lua: the boats and zeppelins of the game,
read from Leatrix Maps (the Forever edition, which also knows the routes this
server added). Each dock there says its zone, where it is, which faction uses
it and which zone it sails to; the two ends of a trip are paired from that.

    python tools/make_transports.py [path to Leatrix_Maps_Icons.lua]

A trip found from both ends is used both ways. A dock whose destination has no
dock sailing back is a leg of a round trip (Southshore -> Auberdine ->
Menethil -> Southshore): it lands at the only dock of its destination left
unpaired, and is used one way only. The Deeprun Tram goes in too: its
"docks" are the entrances in Stormwind and Ironforge.
"""
import os
import re
import sys

DEFAULT = r"D:\BNetGames\World of Warcraft\_forever_\Interface\AddOns\Leatrix_Maps\Leatrix_Maps_Icons.lua"
OUT = os.path.join(os.path.dirname(__file__), "..", "Baquiano", "TransportData.lua")

ZONE = re.compile(r'--\[\[(.*?)\]\]\s*\[(\d+)\]\s*=\s*\{')
DOCK = re.compile(r'\{"Travel([AHN])",\s*([\d.]+),\s*([\d.]+),\s*(.*?),\s*nil,.*,\s*(\d+)\},')


def read(path):
    docks, zone = [], None
    for line in open(path, encoding="utf-8"):
        m = ZONE.search(line)
        if m:
            zone = (m.group(1), int(m.group(2)))
            continue
        m = DOCK.search(line)
        if not m or zone is None:
            continue
        text = re.sub(r'L\["(.*?)"\]', r"\1", m.group(4))
        text = re.sub(r'\s*\.\.\s*"\s*"\s*\.\.\s*|\s*\.\.\s*', " ", text).replace(' ", " ', ", ").strip()
        docks.append({
            "zoneName": zone[0], "zone": zone[1], "faction": m.group(1),
            "x": float(m.group(2)) / 100, "y": float(m.group(3)) / 100,
            "to": int(m.group(5)),
            "kind": "zeppelin" if text.startswith("Zeppelin") else "tram" if text.startswith("Tram") else "boat",
            "text": text,
        })
    return docks


def pair(docks):
    trips, used = [], set()
    # Both ends sail to each other.
    for i, a in enumerate(docks):
        if i in used:
            continue
        for j, b in enumerate(docks):
            if j != i and j not in used and a["to"] == b["zone"] and b["to"] == a["zone"] \
                    and a["kind"] == b["kind"]:
                trips.append((a, b, True))
                used.update((i, j))
                break
    # Legs of a round trip: the only unpaired dock of the destination.
    left = [i for i in range(len(docks)) if i not in used]
    for i in left:
        a = docks[i]
        ends = [docks[j] for j in left if j != i and docks[j]["zone"] == a["to"]]
        if len(ends) == 1:
            trips.append((a, ends[0], False))
        else:
            print("not paired:", a["zoneName"], a["text"], file=sys.stderr)
    return trips


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else DEFAULT
    trips = pair(read(path))
    out = [
        "-- Generated by tools/make_transports.py from Leatrix Maps. Do not edit.",
        "-- { mapID, x, y, mapID, x, y, faction (A, H or N), both ways, kind }",
        "local ADDON, ns = ...",
        "ns.TransportData = {",
    ]
    for a, b, both in trips:
        out.append('    { %d, %.3f, %.3f, %d, %.3f, %.3f, "%s", %s, "%s" }, -- %s: %s'
                   % (a["zone"], a["x"], a["y"], b["zone"], b["x"], b["y"], a["faction"],
                      "true" if both else "false", a["kind"], a["zoneName"], a["text"]))
    out.append("}")
    with open(OUT, "w", encoding="utf-8", newline="\r\n") as f:
        f.write("\n".join(out) + "\n")
    print("%d trips written to %s" % (len(trips), os.path.normpath(OUT)))


if __name__ == "__main__":
    main()
