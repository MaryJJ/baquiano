"""Generate Baquiano/FlightData.lua: flight masters and the flights between them,
and the towns that belong to one faction (those with a flight master for only
one side), so routes can keep away from the other faction's towns.

Data comes from the game's own tables (TaxiNodes, TaxiPath, TaxiPathNode) as
published by wago.tools for the World of Warcraft: Forever client.
Run again when the game updates:

    python3 tools/make_flights.py            # latest Forever build
    python3 tools/make_flights.py 1.60.1.70938
"""
import csv
import io
import json
import math
import os
import sys
import urllib.request

PRODUCT = "wowf"  # World of Warcraft: Forever
UA = {"User-Agent": "Mozilla/5.0 (baquiano make_flights)"}
OUT = os.path.join(os.path.dirname(__file__), "..", "Baquiano", "FlightData.lua")


def fetch(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers=UA)) as r:
        return r.read().decode("utf-8")


def latest_build():
    builds = json.loads(fetch("https://wago.tools/api/builds"))
    return builds[PRODUCT][0]["version"]


def table(name, build):
    text = fetch(f"https://wago.tools/db2/{name}/csv?build={build}")
    if text.startswith("{"):
        sys.exit(f"{name}: {text}")
    return list(csv.DictReader(io.StringIO(text)))


def lua_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    build = sys.argv[1] if len(sys.argv) > 1 else latest_build()
    print("build", build)
    # Only real flight masters: boats, zeppelins and other transports have no
    # flying mount for either faction.
    nodes = {int(r["ID"]): r for r in table("TaxiNodes", build)
             if r["MountCreatureID_0"] != "0" or r["MountCreatureID_1"] != "0"}
    paths = table("TaxiPath", build)
    points = {}
    for r in table("TaxiPathNode", build):
        points.setdefault(int(r["PathID"]), []).append(r)

    flights, used = [], set()
    for p in paths:
        pid, a, b = int(p["ID"]), int(p["FromTaxiNode"]), int(p["ToTaxiNode"])
        if a not in nodes or b not in nodes:
            continue
        pts = sorted(points.get(pid, []), key=lambda r: int(r["NodeIndex"]))
        # Length in the air, only between points on the same continent.
        length = 0.0
        for q, r in zip(pts, pts[1:]):
            if q["ContinentID"] == r["ContinentID"]:
                length += math.hypot(float(r["Loc_0"]) - float(q["Loc_0"]),
                                     float(r["Loc_1"]) - float(q["Loc_1"]))
        if length <= 0:
            continue
        flights.append((a, b, round(length)))
        used.update((a, b))

    # Towns of one faction: TaxiNodes Flags bit 1 = Alliance, bit 2 = Horde.
    # A town with a flight master for each side (Booty Bay, Gadgetzan...) is
    # neutral: both are left out.
    NEUTRAL_NEAR = 400  # yards
    sided = []
    for r in nodes.values():
        side = int(r["Flags"]) & 3
        name = r["Name_lang"]
        if side not in (1, 2) or name.startswith(("Quest Path", "zz")):
            continue
        sided.append((r, "A" if side == 1 else "H"))
    towns = []
    for r, side in sided:
        x, y = float(r["Pos_0"]), float(r["Pos_1"])
        neutral = any(o is not r and oside != side and o["ContinentID"] == r["ContinentID"]
                      and math.hypot(float(o["Pos_0"]) - x, float(o["Pos_1"]) - y) <= NEUTRAL_NEAR
                      for o, oside in sided)
        if not neutral:
            towns.append((int(r["ID"]), r["Name_lang"], side, int(r["ContinentID"]), x, y))

    lines = [
        "-- Generated by tools/make_flights.py from wago.tools (" + PRODUCT + " " + build + ").",
        "-- Do not edit: run the script again when the game updates.",
        "-- nodes[id] = { name (enUS), continentID, worldX, worldY }",
        "-- flights = { from, to, yards flown, ... } in threes",
        "-- towns[id] = { name (enUS), \"A\" or \"H\", continentID, worldX, worldY }:",
        "--   the flight master of a town of one faction",
        "local ADDON, ns = ...",
        "",
        "ns.FlightData = {",
        "    build = " + lua_string(build) + ",",
        "    nodes = {",
    ]
    for nid in sorted(used):
        r = nodes[nid]
        lines.append("        [%d] = { %s, %d, %.1f, %.1f }," % (
            nid, lua_string(r["Name_lang"]), int(r["ContinentID"]),
            float(r["Pos_0"]), float(r["Pos_1"])))
    lines.append("    },")
    lines.append("    flights = {")
    for a, b, length in sorted(flights):
        lines.append("        %d, %d, %d," % (a, b, length))
    lines.append("    },")
    lines.append("    towns = {")
    for tid, name, side, cont, x, y in sorted(towns):
        lines.append("        [%d] = { %s, \"%s\", %d, %.1f, %.1f }," % (tid, lua_string(name), side, cont, x, y))
    lines.append("    },")
    lines.append("}")

    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{len(used)} flight masters, {len(flights)} flights, {len(towns)} towns of one faction"
          f" -> {os.path.normpath(OUT)}")


if __name__ == "__main__":
    main()
